import type { GameMode, VerbUse } from "./types";

// Game archetypes: proven shapes of fun, adapted to Board.
//
// The Studio starts every kid's idea by matching it to an archetype (or two),
// then fills the skeleton recipe with the kid's characters, place and twist.
// `playable` archetypes have a fully built starter game; the rest have
// skeletons whose verbs are designed and get built as we go.
//
// Fun targets use the MDA aesthetics and Lazzaro's 4 keys (see
// docs/research/FUN_RESEARCH.md). Every archetype must include People fun.

export type Aesthetic =
  | "sensation" | "fantasy" | "narrative" | "challenge"
  | "fellowship" | "discovery" | "expression" | "submission";
export type FunKey = "hard" | "easy" | "people" | "serious";

export interface Archetype {
  id: string;
  name: string;
  loop: string; // the 10-second core loop
  boardHook: string; // why it's better on Board than a tablet
  inspiredBy: string[];
  aesthetics: Aesthetic[];
  keys: FunKey[];
  modes: GameMode[];
  ages: [number, number];
  /** What the youngest player does (must work without reading). */
  littlestRole: string;
  /** Toy mode: the same game with no goal. */
  toyMode: string;
  /** What makes each round different, so it stays fresh. */
  twist: string;
  needsPhones: boolean;
  printIdeas: string[];
  verbs: string[];
  skeleton: VerbUse[];
  status: "playable" | "next" | "template";
  starter?: string; // recipe id
}

